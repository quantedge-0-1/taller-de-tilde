export function getVersiculoDelDia(): { versiculo: Versiculo; sesion: "mañana" | "tarde" } {
  const now = new Date();
  const inicio = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - inicio.getTime();
  const dayOfYear = Math.floor(diff / 86400000);

  const hours = now.getHours();
  const esMañana = hours >= 6 && hours < 18;

  const morningIndex = (dayOfYear * 2) % 200;
  const eveningIndex = (dayOfYear * 2 + 1) % 200;

  const index = esMañana ? morningIndex : eveningIndex;
  return {
    versiculo: versiculos[index],
    sesion: esMañana ? "mañana" : "tarde",
  };
}

export function getProximoCambio(): Date {
  const now = new Date();
  const hours = now.getHours();
  const next = new Date(now);

  if (hours < 6) {
    next.setHours(6, 0, 0, 0);
  } else if (hours < 18) {
    next.setHours(18, 0, 0, 0);
  } else {
    next.setDate(next.getDate() + 1);
    next.setHours(6, 0, 0, 0);
  }
  return next;
}
